function generateId() {
  return `TCK-${Date.now().toString(36).toUpperCase()}-${Math.random()
    .toString(36)
    .slice(2, 6)
    .toUpperCase()}`;
}

function formatTime(isoString) {
  if (!isoString) return "";
  const d = new Date(isoString);
  return d.toLocaleString(undefined, {
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
    day: "2-digit",
    month: "short",
  });
}

function arrayBufferToBase64(buffer) {
  const bytes = new Uint8Array(buffer);
  let binary = "";
  bytes.forEach((b) => (binary += String.fromCharCode(b)));
  return btoa(binary);
}

// Signs `${id}|${name}|${email}` with HMAC-SHA256 so a hand-typed or edited
// payload can be told apart from one that was genuinely generated by this app.
async function hmacSign(message, secret) {
  const enc = new TextEncoder();
  const key = await crypto.subtle.importKey(
    "raw",
    enc.encode(secret),
    { name: "HMAC", hash: "SHA-256" },
    false,
    ["sign"]
  );
  const sigBuffer = await crypto.subtle.sign("HMAC", key, enc.encode(message));
  return arrayBufferToBase64(sigBuffer);
}

async function signPayload({ id, name, email }) {
  const sig = await hmacSign(`${id}|${name}|${email}`, QR_SECRET);
  return { id, name, email, sig };
}

async function verifySignature(payload) {
  if (!payload || !payload.id || !payload.name || !payload.email || !payload.sig) {
    return false;
  }
  const expected = await hmacSign(`${payload.id}|${payload.name}|${payload.email}`, QR_SECRET);
  return expected === payload.sig;
}

// Web Audio beeps — no external audio asset needed.
function playBeep({ frequency = 880, duration = 150, type = "sine" } = {}) {
  try {
    const AudioCtx = window.AudioContext || window.webkitAudioContext;
    if (!AudioCtx) return;
    const ctx = new AudioCtx();
    const oscillator = ctx.createOscillator();
    const gain = ctx.createGain();
    oscillator.type = type;
    oscillator.frequency.value = frequency;
    gain.gain.setValueAtTime(0.15, ctx.currentTime);
    gain.gain.exponentialRampToValueAtTime(0.0001, ctx.currentTime + duration / 1000);
    oscillator.connect(gain);
    gain.connect(ctx.destination);
    oscillator.start();
    oscillator.stop(ctx.currentTime + duration / 1000);
    oscillator.onended = () => ctx.close();
  } catch {
    // Audio isn't critical to the flow — fail silently if unsupported/blocked.
  }
}
