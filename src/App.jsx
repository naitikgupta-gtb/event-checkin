// Photo capture — used at registration. Live camera preferred, file upload
// as a fallback for devices without one / permission denied.
// ────────────────────────────────────────────────────────────────────────
function PhotoCapture({ value, onChange, error }) {
  const videoRef = useRef(null);
  const streamRef = useRef(null);
  const [cameraOn, setCameraOn] = useState(false);
  const [camError, setCamError] = useState(null);

  async function startCamera() {
    try {
      const stream = await navigator.mediaDevices.getUserMedia({ video: { facingMode: "user" } });
      streamRef.current = stream;
      // Just flip the flag here — the <video> element doesn't exist in the
      // DOM yet on this render pass (cameraOn was still false when this
      // function started), so we attach the stream in the effect below,
      // which runs *after* React has actually mounted the <video> tag.
      setCameraOn(true);
      setCamError(null);
    } catch {
      setCamError("Camera unavailable — upload a photo instead.");
    }
  }

  // Runs after the <video> element is in the DOM (cameraOn just flipped to
  // true), so videoRef.current is guaranteed to exist here.
  useEffect(() => {
    if (cameraOn && videoRef.current && streamRef.current) {
      videoRef.current.srcObject = streamRef.current;
      videoRef.current.play().catch(() => {
        // Autoplay can be blocked in rare cases — the visible "Capture"
        // button still lets the user try again after interacting with the page.
      });
    }
  }, [cameraOn]);

  function stopCamera() {
    streamRef.current?.getTracks().forEach((t) => t.stop());
    streamRef.current = null;
    setCameraOn(false);
  }

  // Always release the camera when this component goes away.
  useEffect(() => () => stopCamera(), []);

  function capture() {
    const video = videoRef.current;
    if (!video || !video.videoWidth) return;
    const dataUrl = drawSquareToDataUrl(video, video.videoWidth, video.videoHeight);
    onChange(dataUrl);
    stopCamera();
  }

  function handleFile(e) {
    const file = e.target.files?.[0];
    if (!file) return;
    const reader = new FileReader();
    reader.onload = () => {
      const img = new Image();
      img.onload = () => {
        onChange(drawSquareToDataUrl(img, img.width, img.height));
      };
      img.src = reader.result;
    };
    reader.readAsDataURL(file);
  }

  return (
    <div>
      <label className="text-sm font-medium">Photo (required for identity verification)</label>

      {value ? (
        <div className="mt-2 flex items-center gap-3">
          <img src={value} alt="Captured" className="h-20 w-20 rounded-xl object-cover border border-slate-200 dark:border-neutral-800" />
          <button
            type="button"
            onClick={() => onChange(null)}
            className="inline-flex items-center gap-1.5 rounded-lg border border-slate-200 dark:border-neutral-800 hover:bg-slate-100 dark:hover:bg-neutral-800 text-xs font-medium px-3 py-1.5"
          >
            <RefreshCw className="h-3.5 w-3.5" />
            Retake
          </button>
        </div>
      ) : (
        <div className="mt-2 space-y-2">
          {cameraOn ? (
            <div className="space-y-2">
              <video ref={videoRef} muted playsInline className="w-40 h-40 rounded-xl object-cover border border-slate-200 dark:border-neutral-800 bg-black" />
              <div className="flex gap-2">
                <button type="button" onClick={capture} className="rounded-lg bg-indigo-600 hover:bg-indigo-500 text-white text-xs font-medium px-3 py-1.5">
                  Capture
                </button>
                <button type="button" onClick={stopCamera} className="rounded-lg border border-slate-200 dark:border-neutral-800 hover:bg-slate-100 dark:hover:bg-neutral-800 text-xs font-medium px-3 py-1.5">
                  Cancel
                </button>
              </div>
            </div>
          ) : (
            <div className="flex flex-wrap gap-2">
              <button type="button" onClick={startCamera} className="inline-flex items-center gap-1.5 rounded-lg border border-slate-200 dark:border-neutral-800 hover:bg-slate-100 dark:hover:bg-neutral-800 text-xs font-medium px-3 py-1.5">
                <Camera className="h-3.5 w-3.5" />
                Use camera
              </button>
              <label className="inline-flex items-center gap-1.5 rounded-lg border border-slate-200 dark:border-neutral-800 hover:bg-slate-100 dark:hover:bg-neutral-800 text-xs font-medium px-3 py-1.5 cursor-pointer">
                <ImagePlus className="h-3.5 w-3.5" />
                Upload photo
                <input type="file" accept="image/*" onChange={handleFile} className="hidden" />
              </label>
            </div>
          )}
          {camError && <p className="text-xs text-slate-400">{camError}</p>}
        </div>
      )}
      {error && <p className="text-xs text-red-500 mt-1">{error}</p>}
    </div>
  );
}

