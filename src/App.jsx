// ────────────────────────────────────────────────────────────────────────
// Tab 3 — Attendance Dashboard
// ────────────────────────────────────────────────────────────────────────
function AttendanceDashboard({ participants }) {
  const [query, setQuery] = useState("");
  const [filter, setFilter] = useState("all");

  const filtered = useMemo(() => {
    const q = query.trim().toLowerCase();
    return participants
      .filter((p) => (filter === "attended" ? p.attended : filter === "pending" ? !p.attended : true))
      .filter((p) => !q || p.name.toLowerCase().includes(q) || p.email.toLowerCase().includes(q) || p.id.toLowerCase().includes(q))
      .sort((a, b) => {
        if (a.attended && b.attended) return new Date(b.checkedInAt) - new Date(a.checkedInAt);
        if (a.attended !== b.attended) return a.attended ? -1 : 1;
        return a.name.localeCompare(b.name);
      });
  }, [participants, query, filter]);

  const filters = [
    { id: "all", label: "All" },
    { id: "attended", label: "Attended" },
    { id: "pending", label: "Pending" },
  ];

  return (
    <div className="space-y-4">
      <div className="rounded-2xl border border-slate-200 dark:border-neutral-800 bg-white dark:bg-neutral-900 p-4 sm:p-5 shadow-sm">
        <div className="flex flex-col sm:flex-row gap-3 sm:items-center sm:justify-between">
          <div className="relative flex-1">
            <Search className="h-4 w-4 absolute left-3 top-1/2 -translate-y-1/2 text-slate-400" />
            <input
              type="text"
              value={query}
              onChange={(e) => setQuery(e.target.value)}
              placeholder="Search by name, email, or ticket ID…"
              className="w-full rounded-lg border border-slate-200 dark:border-neutral-800 bg-slate-50 dark:bg-neutral-950 pl-9 pr-3 py-2 text-sm outline-none focus:ring-2 focus:ring-indigo-500"
            />
          </div>
          <div className="flex gap-1 rounded-lg border border-slate-200 dark:border-neutral-800 p-1 self-start">
            {filters.map((f) => (
              <button
                key={f.id}
                onClick={() => setFilter(f.id)}
                className={`rounded-md px-3 py-1 text-xs font-medium transition-colors ${
                  filter === f.id ? "bg-indigo-600 text-white" : "text-slate-500 dark:text-slate-400 hover:bg-slate-100 dark:hover:bg-neutral-800"
                }`}
              >
                {f.label}
              </button>
            ))}
          </div>
        </div>
      </div>

      <div className="rounded-2xl border border-slate-200 dark:border-neutral-800 bg-white dark:bg-neutral-900 shadow-sm overflow-hidden">
        {filtered.length === 0 ? (
          <div className="p-10 text-center text-sm text-slate-400">No participants match your search.</div>
        ) : (
          <ul className="divide-y divide-slate-100 dark:divide-slate-800">
            {filtered.map((p) => (
              <li key={p.id} className="flex items-center justify-between gap-3 px-4 sm:px-5 py-3">
                <div className="flex items-center gap-3 min-w-0">
                  {p.photo ? (
                    <img src={p.photo} alt={p.name} className="h-9 w-9 rounded-full object-cover shrink-0 border border-slate-200 dark:border-neutral-800" />
                  ) : (
                    <div className="h-9 w-9 rounded-full bg-slate-100 dark:bg-slate-800 shrink-0" />
                  )}
                  <div className="min-w-0">
                    <p className="text-sm font-medium truncate">{p.name}</p>
                    <p className="text-xs text-slate-500 dark:text-slate-400 truncate">
                      {p.email} · <span className="font-mono">{p.id}</span>
                    </p>
                  </div>
                </div>

                <div className="shrink-0 text-right">
                  {p.attended ? (
                    <span className="inline-flex items-center gap-1 rounded-full bg-emerald-50 dark:bg-emerald-500/10 text-emerald-700 dark:text-emerald-400 text-xs font-medium px-2.5 py-1">
                      <CheckCircle2 className="h-3.5 w-3.5" />
                      Attended
                    </span>
                  ) : (
                    <span className="inline-flex items-center gap-1 rounded-full bg-slate-100 dark:bg-slate-800 text-slate-500 dark:text-slate-400 text-xs font-medium px-2.5 py-1">
                      Pending
                    </span>
                  )}
                  {p.attended && <p className="text-[11px] text-slate-400 mt-1">{formatTime(p.checkedInAt)}</p>}
                </div>
              </li>
            ))}
          </ul>
        )}
      </div>
    </div>
  );
}
