// Tab 2 — Admin QR Scanner
// ────────────────────────────────────────────────────────────────────────
const SCANNER_ELEMENT_ID = "qr-scanner-viewport";

function AdminScanner({ resolveScan, commitCheckIn }) {
  return (
    <AdminPinGate>
      <ScannerInner resolveScan={resolveScan} commitCheckIn={commitCheckIn} />
    </AdminPinGate>
  );
}

function ScannerInner({ resolveScan, commitCheckIn }) {
  const [manualMode, setManualMode] = useState(false);
  const [manualInput, setManualInput] = useState("");
  const [cameraError, setCameraError] = useState(null);
  const [isScanning, setIsScanning] = useState(false);
  const [banner, setBanner] = useState(null);
  const [errorModal, setErrorModal] = useState(null); // reason string
  const [confirmTarget, setConfirmTarget] = useState(null); // participant pending confirmation

  const html5QrCodeRef = useRef(null);
  const lastScanRef = useRef({ value: null, at: 0 });
  // A ref instead of state — "busy" only guards against overlapping async
  // resolutions and must NEVER trigger a re-render or effect re-run, since
  // that was exactly what caused the camera to restart mid-initialization
  // and crash with "Cannot stop, scanner is not running or paused."
  const busyRef = useRef(false);
  // html5-qrcode's internal state machine only allows pause()/resume() once
  // start() has truly resolved — track that with a ref too.
  const scannerReadyRef = useRef(false);

  const pauseScanner = useCallback(() => {
    const instance = html5QrCodeRef.current;
    if (instance && scannerReadyRef.current) {
      try {
        instance.pause(true);
      } catch {
        // Ignore — instance may already be stopped/paused.
      }
    }
  }, []);

  const resumeScanner = useCallback(() => {
    const instance = html5QrCodeRef.current;
    if (instance && scannerReadyRef.current) {
      try {
        instance.resume();
      } catch {
        // Ignore — instance may not be in a paused state.
      }
    }
  }, []);

  // Central handler for both camera decodes and manual submissions.
  const handleDecoded = useCallback(
    async (decodedText) => {
      const now = Date.now();
      if (lastScanRef.current.value === decodedText && now - lastScanRef.current.at < 2000) {
        return;
      }
      lastScanRef.current = { value: decodedText, at: now };

      if (busyRef.current) return;
      busyRef.current = true;
      const result = await resolveScan(decodedText);
      busyRef.current = false;

      if (result.status === "pending-confirm") {
        pauseScanner();
        setBanner(null);
        setErrorModal(null);
        setConfirmTarget(result.participant);
      } else if (result.status === "duplicate") {
        playErrorBeep();
        setErrorModal(null);
        setBanner({
          type: "duplicate",
          message: `Already Checked In at ${formatTime(result.participant.checkedInAt)}`,
        });
      } else {
        playErrorBeep();
        setBanner(null);
        setErrorModal(result.reason);
      }
    },
    [resolveScan, pauseScanner]
  );

  // Keep a ref to the latest handleDecoded so the camera-lifecycle effect
  // below never needs handleDecoded in its dependency array. That's the
  // key fix: the effect must only run when manualMode toggles (or on
  // mount/unmount) — not every time internal scan state changes.
  const handleDecodedRef = useRef(handleDecoded);
  useEffect(() => {
    handleDecodedRef.current = handleDecoded;
  }, [handleDecoded]);

  // ── Camera lifecycle ────────────────────────────────────────────────
  useEffect(() => {
    if (manualMode) return;

    let cancelled = false;
    let qr;
    try {
      qr = new Html5Qrcode(SCANNER_ELEMENT_ID);
    } catch (err) {
      setIsScanning(false);
      setCameraError("Could not initialize the scanner: " + (err?.message || String(err)));
      return; // nothing to clean up — constructor never succeeded
    }
    html5QrCodeRef.current = qr;
    scannerReadyRef.current = false;

    qr.start(
      { facingMode: "environment" },
      { fps: 10, qrbox: { width: 250, height: 250 } },
      (decodedText) => {
        if (!cancelled) handleDecodedRef.current(decodedText);
      },
      () => {
        // Per-frame "no QR found" — expected constantly, ignore.
      }
    )
      .then(() => {
        if (!cancelled) {
          scannerReadyRef.current = true;
          setIsScanning(true);
          setCameraError(null);
        }
      })
      .catch((err) => {
        if (!cancelled) {
          setIsScanning(false);
          setCameraError(typeof err === "string" ? err : err?.message || "Camera access denied or unavailable.");
        }
      });

    return () => {
      cancelled = true;
      const instance = html5QrCodeRef.current;
      // stop() throws SYNCHRONOUSLY (not a rejected promise) if start()
      // hadn't fully finished yet — a real try/catch around the call
      // itself is required, a .catch() on the promise chain is not enough.
      if (instance && scannerReadyRef.current) {
        try {
          instance
            .stop()
            .then(() => instance.clear())
            .catch(() => {});
        } catch {
          try {
            instance.clear();
          } catch {
            /* nothing more we can do — instance is being discarded anyway */
          }
        }
      }
      scannerReadyRef.current = false;
      setIsScanning(false);
    };
  }, [manualMode]);

  function handleManualSubmit(e) {
    e.preventDefault();
    if (!manualInput.trim()) return;
    handleDecoded(manualInput.trim());
    setManualInput("");
  }

  async function handleConfirm() {
    if (!confirmTarget) return;
    const updated = await commitCheckIn(confirmTarget.id);
    setConfirmTarget(null);
    if (updated) {
      playSuccessBeep();
      fireConfetti();
      setBanner({ type: "success", message: `${updated.name} checked in successfully.` });
    } else {
      playErrorBeep();
      setBanner({ type: "duplicate", message: "Check-in failed — please try scanning again." });
    }
    resumeScanner();
  }

  function handleReject() {
    setConfirmTarget(null);
    setBanner({ type: "duplicate", message: "Check-in cancelled — photo did not match, or wrong person." });
    resumeScanner();
  }

  return (
    <div className="max-w-2xl mx-auto space-y-4">
      <div className="rounded-2xl border border-slate-200 dark:border-neutral-800 bg-white dark:bg-neutral-900 p-5 sm:p-6 shadow-sm">
        <div className="flex items-center justify-between gap-3 flex-wrap">
          <h2 className="font-display text-lg font-semibold tracking-wide uppercase flex items-center gap-2">
            <ScanLine className="h-5 w-5 text-indigo-600 dark:text-indigo-400" />
            Admin QR Scanner
            <ShieldCheck className="h-4 w-4 text-emerald-500" title="Admin session active" />
          </h2>

          <button
            onClick={() => {
              setManualMode((m) => !m);
              setCameraError(null);
              setBanner(null);
              setConfirmTarget(null);
            }}
            className={`inline-flex items-center gap-1.5 rounded-lg px-3 py-1.5 text-xs font-medium border transition-colors ${
              manualMode ? "bg-indigo-600 text-white border-indigo-600" : "border-slate-200 dark:border-neutral-800 hover:bg-slate-100 dark:hover:bg-neutral-800"
            }`}
          >
            <KeyRound className="h-3.5 w-3.5" />
            {manualMode ? "Manual entry ON" : "Simulate manual scan"}
          </button>
        </div>

        {banner && (
          <div
            className={`mt-4 rounded-xl px-4 py-3 flex items-start gap-2.5 text-sm ${
              banner.type === "success"
                ? "bg-emerald-50 text-emerald-800 border border-emerald-200 dark:bg-emerald-500/10 dark:text-emerald-300 dark:border-emerald-500/30"
                : "bg-amber-50 text-amber-800 border border-amber-200 dark:bg-amber-500/10 dark:text-amber-300 dark:border-amber-500/30"
            }`}
          >
            {banner.type === "success" ? <CheckCircle2 className="h-4 w-4 mt-0.5 shrink-0" /> : <AlertTriangle className="h-4 w-4 mt-0.5 shrink-0" />}
            <span>{banner.message}</span>
          </div>
        )}

        {!manualMode ? (
          <div className="mt-4">
            <div id={SCANNER_ELEMENT_ID} className="w-full aspect-square max-w-sm mx-auto rounded-xl overflow-hidden border border-slate-200 dark:border-neutral-800 bg-neutral-950" />
            <div className="mt-3 flex items-center justify-center gap-2 text-xs">
              {isScanning ? (
                <span className="inline-flex items-center gap-1.5 text-emerald-600 dark:text-emerald-400">
                  <Camera className="h-3.5 w-3.5" /> Camera active — point at a QR ticket
                </span>
              ) : cameraError ? (
                <span className="inline-flex items-center gap-1.5 text-red-500">
                  <CameraOff className="h-3.5 w-3.5" /> {cameraError}
                </span>
              ) : (
                <span className="inline-flex items-center gap-1.5 text-slate-400">
                  <Camera className="h-3.5 w-3.5" /> Initializing camera…
                </span>
              )}
            </div>
            {cameraError && (
              <p className="mt-2 text-center text-xs text-slate-500 dark:text-slate-400">
                Camera unavailable. Use{" "}
                <button onClick={() => setManualMode(true)} className="underline text-indigo-600 dark:text-indigo-400">
                  manual entry
                </button>{" "}
                instead.
              </p>
            )}
          </div>
        ) : (
          <form onSubmit={handleManualSubmit} className="mt-4 space-y-3">
            <label className="text-sm font-medium">Paste / type signed QR payload</label>
            <textarea
              value={manualInput}
              onChange={(e) => setManualInput(e.target.value)}
              rows={3}
              placeholder='{"id":"TCK-XXXX","name":"...","email":"...","sig":"..."}'
              className="w-full rounded-lg border border-slate-200 dark:border-neutral-800 bg-slate-50 dark:bg-neutral-950 px-3 py-2 text-sm font-mono outline-none focus:ring-2 focus:ring-indigo-500"
            />
            <p className="text-xs text-slate-400">
              A payload without a valid "sig" field (e.g. hand-typed from a copied ID) will always be rejected.
            </p>
            <button type="submit" className="w-full rounded-lg bg-indigo-600 hover:bg-indigo-500 text-white text-sm font-medium py-2 transition-colors">
              Submit Check-In
            </button>
          </form>
        )}
      </div>

      {confirmTarget && (
        <ConfirmIdentityModal participant={confirmTarget} onConfirm={handleConfirm} onReject={handleReject} />
      )}

      {errorModal && <ErrorModal reason={errorModal} onClose={() => setErrorModal(null)} />}
    </div>
  );
}

